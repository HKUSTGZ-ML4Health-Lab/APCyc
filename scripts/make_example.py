#!/usr/bin/env python3
"""Create an original synthetic interface fixture; it is not a biological benchmark."""
import argparse
import json
import math
from pathlib import Path


def create(out):
    out.mkdir(parents=True, exist_ok=False)
    lines, serial = [], 1
    # Deterministic artificial coordinates with a non-collinear receptor pocket.
    # Inference uses the receptor only; the ligand serves input/descriptor examples.
    for chain, count, offset in [('R', 12, 0.0), ('L', 8, 8.0)]:
        for i in range(count):
            angle = i * math.radians(100)
            ca = [2.3 * math.cos(angle), 2.3 * math.sin(angle) + offset, i * 1.5]
            for name, delta in [('N', (-1.1, .4, -.7)), ('CA', (0, 0, 0)),
                                ('C', (1.2, -.2, .8)), ('O', (1.8, .5, 1.2)),
                                ('CB', (-.2, 1.4, .5))]:
                x, y, z = [a+b for a,b in zip(ca, delta)]
                lines.append(f'ATOM  {serial:5d} {name:>4s} ALA {chain}{i+1:4d}    '
                             f'{x:8.3f}{y:8.3f}{z:8.3f}  1.00  0.00          {name[0]:>2s}  ')
                serial += 1
        lines.append('TER')
    (out/'synthetic.pdb').write_text('\n'.join(lines+['END'])+'\n')
    (out/'pocket.json').write_text(json.dumps([['R',[i,' ']] for i in range(1,13)])+'\n')
    row = dict(sample_id='synthetic', complex_pdb='synthetic.pdb', pocket_json='pocket.json',
               receptor_chain='R', peptide_chain='L', peptide_length=8,
               provenance='procedurally generated nonbiological software fixture')
    (out/'manifest.jsonl').write_text(json.dumps(row)+'\n')
    (out/'README.txt').write_text('Synthetic software fixture generated by APCyc. Not a real target, valid fold, binding pose, or scientific evaluation sample.\n')


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--out', type=Path, required=True)
    create(p.parse_args().out)
